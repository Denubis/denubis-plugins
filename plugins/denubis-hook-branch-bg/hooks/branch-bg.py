#!/usr/bin/env python3
"""Colour tmux panes and the terminal by person, repo, branch, and session.

Every pane gets a title strip of up to four coloured blocks, drawn by tmux from
the pane's own current path and title, so it stays right for Claude, Codex and
plain shells alike and needs no agent session:

    [ person ][ repo ][ branch ][ session ]

Block colours come from one baked table of 40 colours, chosen by Oklab
farthest-point search (``docs/branch-bg-colour-eval.py --text-flip``) so that
black or white label text reads on every one. Person, repo and branch names are
assigned colours through a per-machine registry (lowest free slot first, least
recently seen slot reused when full); session names are hashed because they
churn. The pane field behind the text is a near-black shade of the repo colour,
and the same shade goes to the terminal window by OSC 11 when an agent session
starts there.

Modes:
    branch-bg.py                 SessionStart hook: OSC 11, pane field, ensure
                                 the tmux strip is installed for this server.
    branch-bg.py --strip PATH TITLE
                                 Print the strip format and the field colour
                                 for a pane (called by hooks/branch-strip.sh).

Brian, 2026-10-09: the colour is a highlight, not the field under white text;
one block per person, repo, branch and session; black or white text as needed.
"""

